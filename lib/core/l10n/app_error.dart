/// An app-authored failure whose arguments may include unmodified user data.
abstract interface class LocalizedAppFailure {
  AppErrorCode? get code;
  List<String> get arguments;
  String get message;
}

/// Keeps FormatException compatibility while carrying a typed UI message.
class AppFormatException extends FormatException
    implements LocalizedAppFailure {
  const AppFormatException(
    this.code,
    super.message, [
    this.arguments = const [],
  ]);
  @override
  final AppErrorCode code;
  @override
  final List<String> arguments;
}
