#!/usr/bin/env python3
"""Compile the source-language translation catalog into a synchronous delegate map."""
import json
from pathlib import Path
import subprocess

root = Path(__file__).resolve().parents[1]
source = root / 'assets/l10n/en.json'
values = json.loads(source.read_text())
for key, value in values.items():
    if not isinstance(value, str) or not value.strip():
        raise ValueError(f'Empty translation: {key}')
content = json.dumps(values, ensure_ascii=False, indent=2).replace('$', r'\$')
target = root / 'lib/core/l10n/messages_en.g.dart'
target.write_text('// Generated by scripts/generate_l10n.py. Edit assets/l10n/en.json.\n'
                  'const englishMessages = <String, String>' + content + ';\n')
subprocess.run(['dart', 'format', str(target)], check=True)
